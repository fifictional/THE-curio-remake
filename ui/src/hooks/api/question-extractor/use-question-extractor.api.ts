import { useCallback, useEffect, useState } from 'react';
import { useAmplifyApiClient } from '@/providers/amplify-provider';
import { useSessionContext } from '@/providers/session-provider';
import { uploadData } from 'aws-amplify/storage';
import { v4 as uuidv4 } from 'uuid';

export interface ExtractedQuestion {
  extractedQuestionUuid: string;
  questionExtractJobUuid: string;
  moduleNumber: number; // Module number (1, 2, 3, 4, etc.)
  questionNumber: number; // Question number within the module (1, 2, 3, ...)
  questionContent: string;
  questionType: 'MULTIPLE_CHOICE' | 'TEXT_INPUT';
  questionOptions: string[]; // Empty array for TEXT_INPUT, 4 options for MULTIPLE_CHOICE
  correctAnswer?: string; // For MULTIPLE_CHOICE: "A", "B", "C", or "D". For TEXT_INPUT: the answer string
  answerExplanations?: string[]; // Array of 4 explanations for all answer choices (A, B, C, D order), empty strings if not available
  hint?: string; // Hint for solving the question
  questionReference?: {
    referenceType?: 'none' | 'image' | 'graph' | 'chart' | 'table' | 'passage';
    page: number;
    boundingBox: number[];
    s3Key?: string; // S3 key for uploaded reference image
    text?: string; // Text content for passages, tables, or JSON data for graphs/charts
  };
  needsReference?: boolean; // Whether the question requires a reference (for generated questions)
  referenceGenerationPrompt?: string; // AI-generated prompt for creating the reference (for generated questions)
  referenceExtractionStatus?: 'EXTRACTING' | 'EXTRACTED' | 'FAILED'; // Track reference extraction progress
  referenceExtractionError?: string; // Error message if reference extraction failed
  isGenerated?: boolean; // Whether the question was generated by AI (vs extracted from a document)
  // Metadata
  exam: string; // e.g., "SAT"
  module: string; // e.g., "Math", "Reading and Writing"
  topic?: string; // e.g., "Algebra", "Advanced Math"
  subtopic?: string; // e.g., "Linear equations", "Quadratic equations"
  concept?: string; // e.g., "Solving for x", "Factoring"
  difficulty?: 'EASY' | 'MEDIUM' | 'HARD'; // Difficulty level assessed by AI
  examModuleUuid?: string; // Link to ExamModule
  verified?: boolean; // Whether the question has been manually verified
  verifiedAt?: string; // When the question was verified
  verifiedBy?: string; // User who verified the question
  createdAt: string;
  updatedAt: string;
}

export interface QuestionExtractJob {
  questionExtractJobUuid: string;
  userUuid: string; // Track who created the job
  s3Key: string;
  fileName: string;
  fileType: string;
  status: 'PENDING' | 'PROCESSING' | 'MODULES_EXTRACTED' | 'QUESTION_EXTRACTED' | 'COMPLETED' | 'FAILED';
  totalQuestions?: number;
  error?: string;
  extractionLogs?: string; // Markdown-formatted logs of extraction progress
  identifiedModules?: string; // JSON string of identified modules
  // Answer key fields
  answerKeyS3Key?: string;
  answerKeyFileName?: string;
  answerKeyStatus?: 'PENDING' | 'PROCESSING' | 'ANSWER_MODULES_EXTRACTED' | 'COMPLETED' | 'FAILED';
  answerKeyError?: string;
  identifiedAnswerModules?: string; // JSON string of identified modules from answer key Phase 1
  createdAt: string;
  updatedAt: string;
}

export function useQuestionExtractorApi(jobUuid: string | null) {
  const client = useAmplifyApiClient();
  const { userAttributes } = useSessionContext();
  const [isUploading, setIsUploading] = useState(false);
  const [currentJob, setCurrentJob] = useState<QuestionExtractJob | null>(null);
  const [extractedQuestions, setExtractedQuestions] = useState<ExtractedQuestion[]>([]);
  const [isLoadingQuestions, setIsLoadingQuestions] = useState(false);
  const [isExtractingReferences, setIsExtractingReferences] = useState(false);
  const [extractingReferenceUuids, setExtractingReferenceUuids] = useState<Set<string>>(new Set());

  // Fetch extracted questions when job is completed
  const fetchExtractedQuestions = useCallback(async (jobId: string) => {
    setIsLoadingQuestions(true);
    try {
      const response = await client.models.ExtractedQuestion.listExtractedQuestionByQuestionExtractJobUuidAndModuleNumberAndQuestionNumber(
        { questionExtractJobUuid: jobId },
        {
          sortDirection: 'ASC',
          limit: 1000,
        }
      );
      if (response.data) {
        // Ensure proper sorting by moduleNumber then questionNumber
        const sortedQuestions = [...response.data].sort((a, b) => {
          if (a.moduleNumber !== b.moduleNumber) {
            return a.moduleNumber - b.moduleNumber;
          }
          return a.questionNumber - b.questionNumber;
        });
        setExtractedQuestions(sortedQuestions as ExtractedQuestion[]);
      }
    } catch (error) {
      console.error('Error fetching extracted questions:', error);
    } finally {
      setIsLoadingQuestions(false);
    }
  }, [client]);

  // Subscribe to job updates
  useEffect(() => {
    if (!jobUuid) {
      setCurrentJob(null);
      setExtractedQuestions([]);
      return;
    }

    let isActive = true;

    // Fetch initial job data
    const fetchJob = async () => {
      try {
        const response = await client.models.QuestionExtractJob.get({
          questionExtractJobUuid: jobUuid,
        });
        if (response.data && isActive) {
          setCurrentJob(response.data as QuestionExtractJob);
          // If job is completed or questions are extracted, fetch the questions
          if (response.data.status === 'COMPLETED' || response.data.status === 'QUESTION_EXTRACTED') {
            fetchExtractedQuestions(jobUuid);
          }
        }
      } catch (error) {
        console.error('Error fetching job:', error);
      }
    };
    fetchJob();

    // Subscribe to job updates
    const jobSubscription = client.models.QuestionExtractJob.onUpdate({
      filter: { questionExtractJobUuid: { eq: jobUuid } },
    }).subscribe({
      next: (data) => {
        if (!isActive) return;
        console.log('Job updated:', data);
        setCurrentJob(data as QuestionExtractJob);
        // If job just completed or questions extracted, fetch the questions
        if (data.status === 'COMPLETED' || data.status === 'QUESTION_EXTRACTED') {
          fetchExtractedQuestions(jobUuid);
        }
      },
      error: (error) => {
        console.error('Subscription error:', error);
      },
    });

    // Subscribe to extracted question updates
    const questionSubscription = client.models.ExtractedQuestion.onUpdate({
      filter: { questionExtractJobUuid: { eq: jobUuid } },
    }).subscribe({
      next: (updatedQuestion) => {
        if (!isActive) return;
        console.log('Question updated - UUID:', updatedQuestion.extractedQuestionUuid, 
                    'Status:', updatedQuestion.referenceExtractionStatus, 
                    'S3Key:', updatedQuestion.questionReference?.s3Key ? 'Present' : 'None');
        
        // Remove from extracting set if status is EXTRACTED or FAILED
        if (updatedQuestion.referenceExtractionStatus === 'EXTRACTED' || 
            updatedQuestion.referenceExtractionStatus === 'FAILED') {
          setExtractingReferenceUuids(prev => {
            const newSet = new Set(prev);
            newSet.delete(updatedQuestion.extractedQuestionUuid);
            return newSet;
          });
        }
        
        setExtractedQuestions((prev) => {
          const index = prev.findIndex(q => q.extractedQuestionUuid === updatedQuestion.extractedQuestionUuid);
          if (index !== -1) {
            const newQuestions = [...prev];
            newQuestions[index] = updatedQuestion as ExtractedQuestion;
            console.log(`Updated question ${index + 1} in state with status: ${updatedQuestion.referenceExtractionStatus}`);
            return newQuestions;
          }
          console.warn('Question not found in state:', updatedQuestion.extractedQuestionUuid);
          return prev;
        });
      },
      error: (error) => {
        console.error('Question subscription error:', error);
      },
    });

    return () => {
      isActive = false;
      jobSubscription.unsubscribe();
      questionSubscription.unsubscribe();
    };
  }, [jobUuid, client, fetchExtractedQuestions]);

  const uploadFile = useCallback(async (file: File): Promise<string | null> => {
    if (!userAttributes?.userUuid) {
      console.error('User not authenticated');
      return null;
    }

    setIsUploading(true);

    try {
      // Generate UUIDs
      const questionExtractJobUuid = uuidv4();
      const taskUuid = uuidv4();
      const s3Key = `exam-papers/${userAttributes.userUuid}/${questionExtractJobUuid}/${file.name}`;

      // Upload file to S3
      await uploadData({
        path: s3Key,
        data: file,
        options: {
          contentType: file.type,
        },
      }).result;

      // Create job in database
      const jobResponse = await client.models.QuestionExtractJob.create({
        questionExtractJobUuid,
        userUuid: userAttributes.userUuid,
        s3Key,
        fileName: file.name,
        fileType: file.type.includes('pdf') ? 'pdf' : 'image',
        status: 'PENDING',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });

      if (!jobResponse.data) {
        throw new Error('Failed to create job');
      }

      // Create task for dispatcher (Phase 1: Extract Modules)
      await client.models.Task.create({
        taskUuid,
        userUuid: userAttributes.userUuid,
        type: 'EXTRACT_MODULES',
        status: 'PENDING',
        progress: 0,
        args: JSON.stringify({ 
          questionExtractJobUuid,
          exam: 'SAT',
          type: 'question'
        }),
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });

      console.log('Job and task created successfully');
      return questionExtractJobUuid;
    } catch (error) {
      console.error('Error uploading file:', error);
      alert('Failed to upload file. Please try again.');
      return null;
    } finally {
      setIsUploading(false);
    }
  }, [userAttributes, client]);

  const resetJob = useCallback(() => {
    setCurrentJob(null);
    setExtractedQuestions([]);
  }, []);

  const extractReferences = useCallback(async (questionUuids?: string[]) => {
    if (!currentJob) {
      console.error('No current job to extract references for');
      return false;
    }

    // Determine which questions we're extracting
    const uuidsToExtract = questionUuids || extractedQuestions
      .filter(q => q.questionReference && q.questionReference.referenceType !== 'none')
      .map(q => q.extractedQuestionUuid);

    // Add UUIDs to the extracting set
    setExtractingReferenceUuids(prev => {
      const newSet = new Set(Array.from(prev));
      uuidsToExtract.forEach(uuid => newSet.add(uuid));
      return newSet;
    });
    setIsExtractingReferences(true);
    
    try {
      console.log('Extracting references for job:', currentJob.questionExtractJobUuid);
      console.log('Question UUIDs:', questionUuids || 'all');
      
      const response = await client.mutations.extractQuestionReferences({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
        questionUuids: questionUuids || undefined,
      });

      if (response.data?.success) {
        console.log(`Successfully processed ${response.data.processedCount} references`);
        return true;
      } else {
        console.error('Reference extraction failed');
        alert('Failed to extract references. Please try again.');
        // Remove UUIDs from extracting set on failure
        setExtractingReferenceUuids(prev => {
          const newSet = new Set(prev);
          uuidsToExtract.forEach(uuid => newSet.delete(uuid));
          return newSet;
        });
        return false;
      }
    } catch (error) {
      console.error('Error extracting references:', error);
      alert('Failed to extract references. Please try again.');
      // Remove UUIDs from extracting set on error
      setExtractingReferenceUuids(prev => {
        const newSet = new Set(prev);
        uuidsToExtract.forEach(uuid => newSet.delete(uuid));
        return newSet;
      });
      return false;
    } finally {
      setIsExtractingReferences(false);
    }
  }, [currentJob?.questionExtractJobUuid, client, extractedQuestions.length]);

  // Recrop a single question reference with new bounding box
  // Updates the bounding box in the database, then calls extractQuestionReferences mutation
  const recropReference = useCallback(async (extractedQuestionUuid: string, referenceType: 'image' | 'graph' | 'chart' | 'table' | 'passage', page: number, boundingBox: number[]) => {
    if (!currentJob) {
      console.error('No current job to recrop reference for');
      return false;
    }

    try {
      console.log('Recropping - updating bounding box for question:', extractedQuestionUuid);
      console.log('New bounding box:', boundingBox);
      
      // Find the question to get its current reference data
      const question = extractedQuestions.find(q => q.extractedQuestionUuid === extractedQuestionUuid);
      if (!question || !question.questionReference) {
        console.error('Question or reference not found');
        alert('Question or reference not found');
        return false;
      }

      // Step 1: Update the question's bounding box in the database
      await client.models.ExtractedQuestion.update({
        extractedQuestionUuid,
        questionReference: {
          referenceType,
          page,
          boundingBox,
          s3Key: null,
          text: null,
        },
        referenceExtractionStatus: 'EXTRACTING',
        referenceExtractionError: null,
        updatedAt: new Date().toISOString(),
      });

      console.log('Bounding box updated, calling extractQuestionReferences...');

      // Step 2: Call extractQuestionReferences mutation
      // The Lambda will read the updated bounding box from the database and recrop
      return await extractReferences([extractedQuestionUuid]);

    } catch (error) {
      console.error('Error recropping reference:', error);
      alert('Failed to recrop reference. Please try again.');
      return false;
    }
  }, [currentJob?.questionExtractJobUuid, client, extractedQuestions, extractReferences]);

  // Update a question
  const updateQuestion = useCallback(async (updatedQuestion: ExtractedQuestion) => {
    try {
      console.log('Updating question:', updatedQuestion.extractedQuestionUuid);
      
      // Handle questionReference - ensure complete object structure for custom type
      let questionReference: any = updatedQuestion.questionReference;
      if (questionReference !== undefined && questionReference !== null) {
        // Preserve the referenceType if explicitly set (including falsy values like empty string),
        // only default to 'none' if it's truly undefined/null
        const referenceType = (questionReference.referenceType !== undefined && questionReference.referenceType !== null)
          ? questionReference.referenceType
          : 'none';
        questionReference = {
          referenceType: referenceType,
          page: questionReference.page ?? 0,
          boundingBox: questionReference.boundingBox ?? [],
          s3Key: questionReference.s3Key ?? null,
          text: questionReference.text ?? null,
        };
      }
      
      await client.models.ExtractedQuestion.update({
        extractedQuestionUuid: updatedQuestion.extractedQuestionUuid,
        questionContent: updatedQuestion.questionContent,
        questionOptions: updatedQuestion.questionOptions,
        examModuleUuid: updatedQuestion.examModuleUuid,
        module: updatedQuestion.module,
        topic: updatedQuestion.topic,
        subtopic: updatedQuestion.subtopic,
        concept: updatedQuestion.concept,
        difficulty: updatedQuestion.difficulty,
        correctAnswer: updatedQuestion.correctAnswer,
        answerExplanations: updatedQuestion.answerExplanations,
        hint: updatedQuestion.hint,
        questionReference,
        referenceExtractionStatus: updatedQuestion.referenceExtractionStatus,
        referenceExtractionError: updatedQuestion.referenceExtractionError,
        needsReference: updatedQuestion.needsReference,
        referenceGenerationPrompt: updatedQuestion.referenceGenerationPrompt,
        updatedAt: new Date().toISOString(),
      });

      console.log('Question updated successfully');
      return true;
    } catch (error) {
      console.error('Error updating question:', error);
      throw error;
    }
  }, [client]);

  // Start question extraction (Phase 2)
  const startQuestionExtraction = useCallback(async (modules: any[]) => {
    if (!currentJob || !userAttributes?.userUuid) {
      console.error('No current job or user not authenticated');
      return false;
    }

    try {
      // Update the job with the edited modules
      await client.models.QuestionExtractJob.update({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
        identifiedModules: JSON.stringify(modules),
        updatedAt: new Date().toISOString(),
      });

      // Create task for question extraction
      const taskUuid = uuidv4();
      await client.models.Task.create({
        taskUuid,
        userUuid: userAttributes.userUuid,
        type: 'QUESTION_EXTRACT',
        status: 'PENDING',
        progress: 0,
        args: JSON.stringify({ 
          questionExtractJobUuid: currentJob.questionExtractJobUuid,
        }),
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });

      console.log('Question extraction task created successfully');
      return true;
    } catch (error) {
      console.error('Error starting question extraction:', error);
      alert('Failed to start question extraction. Please try again.');
      return false;
    }
  }, [currentJob, userAttributes, client]);

  // Re-extract modules (restart Phase 1)
  const reExtractModules = useCallback(async () => {
    if (!currentJob || !userAttributes?.userUuid) {
      console.error('No current job or user not authenticated');
      return false;
    }

    try {
      // Update job status back to PROCESSING
      await client.models.QuestionExtractJob.update({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
        status: 'PROCESSING',
        identifiedModules: null,
        updatedAt: new Date().toISOString(),
      });

      // Create a new EXTRACT_MODULES task
      const taskUuid = uuidv4();
      await client.models.Task.create({
        taskUuid,
        userUuid: userAttributes.userUuid,
        type: 'EXTRACT_MODULES',
        status: 'PENDING',
        progress: 0,
        args: JSON.stringify({ 
          questionExtractJobUuid: currentJob.questionExtractJobUuid,
          exam: 'SAT',
          type: 'question'
        }),
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });

      console.log('Module re-extraction task created successfully');
      return true;
    } catch (error) {
      console.error('Error re-extracting modules:', error);
      alert('Failed to re-extract modules. Please try again.');
      return false;
    }
  }, [currentJob, userAttributes, client]);

  // Start answer extraction (Phase 2 for answers)
  const startAnswerExtraction = useCallback(async (modules: any[]) => {
    if (!currentJob || !userAttributes?.userUuid) {
      console.error('No current job or user not authenticated');
      return false;
    }

    try {
      // Update the job with the edited answer modules
      await client.models.QuestionExtractJob.update({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
        identifiedAnswerModules: JSON.stringify(modules),
        answerKeyStatus: 'PROCESSING',
        updatedAt: new Date().toISOString(),
      });

      // Trigger answer extraction mutation
      console.log('Triggering SAT answer key extraction...');
      const response = await client.mutations.satExtractAnswers({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
      });

      if (response.data?.success) {
        console.log(`Successfully extracted ${response.data.matchedCount} answers`);
        return true;
      } else {
        console.error('Answer extraction failed:', response.data?.error);
        alert(`Failed to extract answers: ${response.data?.error || 'Unknown error'}`);
        return false;
      }
    } catch (error) {
      console.error('Error starting answer extraction:', error);
      alert('Failed to start answer extraction. Please try again.');
      return false;
    }
  }, [currentJob, userAttributes, client]);

  // Re-extract answer modules (restart Phase 1 for answers)
  const reExtractAnswerModules = useCallback(async () => {
    if (!currentJob || !userAttributes?.userUuid) {
      console.error('No current job or user not authenticated');
      return false;
    }

    try {
      // Update answer key status back to PROCESSING
      await client.models.QuestionExtractJob.update({
        questionExtractJobUuid: currentJob.questionExtractJobUuid,
        answerKeyStatus: 'PROCESSING',
        identifiedAnswerModules: null,
        updatedAt: new Date().toISOString(),
      });

      // Create a new EXTRACT_ANSWER_MODULES task
      const taskUuid = uuidv4();
      await client.models.Task.create({
        taskUuid,
        userUuid: userAttributes.userUuid,
        type: 'EXTRACT_ANSWER_MODULES',
        status: 'PENDING',
        progress: 0,
        args: JSON.stringify({ 
          questionExtractJobUuid: currentJob.questionExtractJobUuid,
        }),
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });

      console.log('Answer module re-extraction task created successfully');
      return true;
    } catch (error) {
      console.error('Error re-extracting answer modules:', error);
      alert('Failed to re-extract answer modules. Please try again.');
      return false;
    }
  }, [currentJob, userAttributes, client]);

  return {
    uploadFile,
    isUploading,
    currentJob,
    extractedQuestions,
    isLoadingQuestions,
    isExtractingReferences,
    extractingReferenceUuids,
    resetJob,
    extractReferences,
    recropReference,
    updateQuestion,
    startQuestionExtraction,
    reExtractModules,
    startAnswerExtraction,
    reExtractAnswerModules,
  };
}

