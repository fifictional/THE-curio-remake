// Amplify doesn't set CI=true, so treat AWS_APP_ID / AWS_BRANCH as a CI signal.
const isAmplifyBuild = Boolean(process.env.AWS_APP_ID || process.env.AWS_BRANCH);
const isCiBuild = Boolean(process.env.CI) || isAmplifyBuild;

// Prefer explicit SENTRY_RELEASE, then Amplify commit id, then Vercel commit sha.
const resolvedRelease =
  process.env.SENTRY_RELEASE ||
  process.env.NEXT_PUBLIC_SENTRY_RELEASE ||
  process.env.AWS_COMMIT_ID ||
  process.env.VERCEL_GIT_COMMIT_SHA;

if (resolvedRelease && !process.env.SENTRY_RELEASE) {
  process.env.SENTRY_RELEASE = resolvedRelease;
}
if (resolvedRelease && !process.env.NEXT_PUBLIC_SENTRY_RELEASE) {
  process.env.NEXT_PUBLIC_SENTRY_RELEASE = resolvedRelease;
}

const sentryWebpackPluginOptions = {
  org: process.env.SENTRY_ORG,
  project: process.env.SENTRY_PROJECT,
  authToken: process.env.SENTRY_AUTH_TOKEN,
  silent: !isCiBuild,
  telemetry: false,
  widenClientFileUpload: true,
  release: resolvedRelease ? { name: resolvedRelease } : undefined,
  sourcemaps: {
    disable: !process.env.SENTRY_AUTH_TOKEN,
    deleteSourcemapsAfterUpload: true,
  },
};

module.exports = withSentryConfig(nextConfig, sentryWebpackPluginOptions);
